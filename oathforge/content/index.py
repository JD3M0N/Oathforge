"""content/INDEX.md: one line per content id (kind, id, English name, file), written by ``oath content-index``.

An agent finds where an item, NPC or quest lives by reading one line instead of opening the YAML.
``tests/test_content.py`` fails when the file is out of date.
"""

import re
from pathlib import Path

from oathforge.content.loader import Content

# Content field -> its file under content/ (kinds with one file for all ids)
FLAT_FILES = {
    "abilities": "abilities.yaml",
    "skills": "abilities.yaml",
    "lineages": "lineages.yaml",
    "backgrounds": "backgrounds.yaml",
    "specializations": "specializations.yaml",
    "professions": "professions.yaml",
    "entities": "entities.yaml",
    "forms": "forms.yaml",
    "factions": "factions.yaml",
    "achievements": "achievements.yaml",
    "rulebook": "rulebook.yaml",
}
# one folder or file per ficha, found by walking content/: kind -> glob of its ficha, {key} is the id
FOLDER_KINDS = {
    "classes": "classes/{key}/class.yaml",
    "monsters": "monsters/{key}/monster.yaml",
    "items": "items/*/{key}/item.yaml",
    "npcs": "world/*/*/npcs/{key}/npc.yaml",
    "quests": "world/*/*/quests/{key}.yaml",
}
# kinds that share files (several ids per file): kind -> glob of the files
MERGED_KINDS = {
    "class_specializations": "classes/*/specializations.yaml",
    "recipes": "items/*/recipes.yaml",
}
WORLD_KINDS = ("continents", "zones", "locations")
HEADER = "# Content index\n\nGenerated by `oath content-index`; do not edit. One line per id: `id` English name.\n"


def _name(value) -> str:
    for attr in ("name", "title"):
        text = getattr(value, attr, None)
        if text is not None:
            return text.en
    outputs = getattr(value, "outputs", None)  # recipes
    return "→ " + ", ".join(outputs) if outputs else ""


def _world_file(c: Content, kind: str, key: str, directory: Path) -> str:
    if kind == "continents":
        return f"world/{key}/continent.yaml"
    if kind == "zones":
        found = next((directory / "world").glob(f"*/{key}/zone.yaml"))
        return found.relative_to(directory).as_posix()
    loc = c.locations[key]
    return f"world/{loc.continent}/{loc.zone}/{key}/place.yaml"


def _ficha_file(directory: Path, kind: str, key: str) -> str:
    found = next(directory.glob(FOLDER_KINDS[kind].format(key=key)))
    return found.relative_to(directory).as_posix()


def _merged_files(directory: Path, kind: str) -> dict[str, str]:
    """id -> file for the kinds whose ids share files: the top-level keys of each file."""
    out: dict[str, str] = {}
    for path in sorted(directory.glob(MERGED_KINDS[kind])):
        rel = path.relative_to(directory).as_posix()
        out.update({key: rel for key in re.findall(r"^([A-Za-z0-9_]+):", path.read_text(encoding="utf-8"), re.M)})
    return out


def build_index(c: Content, directory: Path) -> str:
    out = [HEADER]
    for kind in WORLD_KINDS:
        entries = getattr(c, kind)
        out.append(f"\n## {kind} ({len(entries)})\n")
        out += [f"- `{key}` {_name(v)} · {_world_file(c, kind, key, directory)}" for key, v in sorted(entries.items())]
    for kind in (*FOLDER_KINDS, *MERGED_KINDS):
        entries = getattr(c, kind)
        out.append(f"\n## {kind} ({len(entries)})\n")
        files = _merged_files(directory, kind) if kind in MERGED_KINDS else {}
        for key, v in sorted(entries.items()):
            file = files[key] if kind in MERGED_KINDS else _ficha_file(directory, kind, key)
            out.append(f"- `{key}` {_name(v)} · {file}".replace("  ·", " ·"))
    for kind, file in FLAT_FILES.items():
        entries = getattr(c, kind)
        out.append(f"\n## {kind} ({len(entries)}) · {file}\n")
        out += [f"- `{key}` {_name(v)}".rstrip() for key, v in sorted(entries.items())]
    return "\n".join(out) + "\n"
